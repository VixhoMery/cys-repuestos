CREATE FUNCTION public.cys_create_product(
  p_name text,
  p_brand text,
  p_sku text,
  p_category text,
  p_supplier_id bigint,
  p_location text,
  p_net_price integer,
  p_price integer,
  p_stock integer,
  p_short_description text,
  p_description text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_id bigint;
  v_location text :=
    NULLIF(BTRIM(COALESCE(p_location, '')), '');
BEGIN
  IF NOT public.cys_is_authorized_user() THEN
    RAISE EXCEPTION 'No autorizado.' USING ERRCODE = '42501';
  END IF;

  IF p_stock IS NULL OR p_stock < 0 THEN
    RAISE EXCEPTION 'El stock no puede ser negativo.';
  END IF;

  IF CHAR_LENGTH(COALESCE(v_location, '')) > 120 THEN
    RAISE EXCEPTION 'La ubicación no puede superar los 120 caracteres.';
  END IF;

  IF
    p_supplier_id IS NOT NULL
    AND NOT EXISTS (
      SELECT 1
      FROM public.suppliers s
      WHERE s.id = p_supplier_id
    )
  THEN
    RAISE EXCEPTION 'El proveedor no existe.'
      USING ERRCODE = '23503';
  END IF;

  INSERT INTO public.products (
    name,
    brand,
    sku,
    category,
    supplier_id,
    location,
    net_price,
    price,
    stock,
    short_description,
    description
  )
  VALUES (
    BTRIM(p_name),
    BTRIM(p_brand),
    BTRIM(p_sku),
    BTRIM(p_category),
    p_supplier_id,
    v_location,
    p_net_price,
    p_price,
    p_stock,
    BTRIM(p_short_description),
    BTRIM(p_description)
  )
  RETURNING id
  INTO v_id;

  RETURN public.cys_get_product(v_id);
END;
$$;


