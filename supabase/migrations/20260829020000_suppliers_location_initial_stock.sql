CREATE OR REPLACE FUNCTION public.cys_list_suppliers()
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_result jsonb;
BEGIN
  IF NOT public.cys_is_authorized_user() THEN
    RAISE EXCEPTION 'No autorizado.' USING ERRCODE = '42501';
  END IF;

  SELECT COALESCE(
    jsonb_agg(
      jsonb_build_object(
        'id', s.id::integer,
        'name', s.name,
        'createdAt', s.created_at,
        'productCount', (
          SELECT COUNT(*)::integer
          FROM public.products p
          WHERE p.supplier_id = s.id
        )
      )
      ORDER BY LOWER(s.name)
    ),
    '[]'::jsonb
  )
  INTO v_result
  FROM public.suppliers s;

  RETURN v_result;
END;
$$;


CREATE OR REPLACE FUNCTION public.cys_create_supplier(
  p_name text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_supplier public.suppliers%ROWTYPE;
BEGIN
  IF NOT public.cys_is_authorized_user() THEN
    RAISE EXCEPTION 'No autorizado.' USING ERRCODE = '42501';
  END IF;

  IF
    NULLIF(BTRIM(COALESCE(p_name, '')), '') IS NULL
  THEN
    RAISE EXCEPTION 'El nombre del proveedor es obligatorio.';
  END IF;

  INSERT INTO public.suppliers (name)
  VALUES (BTRIM(p_name))
  RETURNING *
  INTO v_supplier;

  RETURN jsonb_build_object(
    'id', v_supplier.id::integer,
    'name', v_supplier.name,
    'createdAt', v_supplier.created_at,
    'productCount', 0
  );
END;
$$;


CREATE OR REPLACE FUNCTION public.cys_delete_supplier(
  p_id bigint
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_supplier public.suppliers%ROWTYPE;
  v_product_count integer;
BEGIN
  IF NOT public.cys_is_authorized_user() THEN
    RAISE EXCEPTION 'No autorizado.' USING ERRCODE = '42501';
  END IF;

  SELECT *
  INTO v_supplier
  FROM public.suppliers
  WHERE id = p_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('status', 'not-found');
  END IF;

  SELECT COUNT(*)::integer
  INTO v_product_count
  FROM public.products
  WHERE supplier_id = v_supplier.id;

  IF v_product_count > 0 THEN
    RETURN jsonb_build_object(
      'status', 'in-use',
      'productCount', v_product_count
    );
  END IF;

  DELETE FROM public.suppliers
  WHERE id = p_id;

  RETURN jsonb_build_object(
    'status', 'deleted',
    'supplier',
      jsonb_build_object(
        'id', v_supplier.id::integer,
        'name', v_supplier.name
      )
  );
END;
$$;


