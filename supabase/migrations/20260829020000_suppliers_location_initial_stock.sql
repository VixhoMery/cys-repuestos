CREATE FUNCTION public.cys_update_product(
  p_id bigint,
  p_name text,
  p_brand text,
  p_sku text,
  p_category text,
  p_supplier_id bigint,
  p_location text,
  p_net_price integer,
  p_price integer,
  p_stock integer,
  p_short_description text,
  p_description text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_location text :=
    NULLIF(BTRIM(COALESCE(p_location, '')), '');
BEGIN
  IF NOT public.cys_is_authorized_user() THEN
    RAISE EXCEPTION 'No autorizado.' USING ERRCODE = '42501';
  END IF;

  IF p_stock IS NULL OR p_stock < 0 THEN
    RAISE EXCEPTION 'El stock no puede ser negativo.';
  END IF;

  IF CHAR_LENGTH(COALESCE(v_location, '')) > 120 THEN
    RAISE EXCEPTION 'La ubicación no puede superar los 120 caracteres.';
  END IF;

  IF
    p_supplier_id IS NOT NULL
    AND NOT EXISTS (
      SELECT 1
      FROM public.suppliers s
      WHERE s.id = p_supplier_id
    )
  THEN
    RAISE EXCEPTION 'El proveedor no existe.'
      USING ERRCODE = '23503';
  END IF;

  UPDATE public.products
  SET
    name = BTRIM(p_name),
    brand = BTRIM(p_brand),
    sku = BTRIM(p_sku),
    category = BTRIM(p_category),
    supplier_id = p_supplier_id,
    location = v_location,
    net_price = p_net_price,
    price = p_price,
    stock = p_stock,
    short_description = BTRIM(p_short_description),
    description = BTRIM(p_description),
    updated_at = NOW()
  WHERE id = p_id;

  IF NOT FOUND THEN
    RETURN NULL;
  END IF;

  RETURN public.cys_get_product(p_id);
END;
$$;


