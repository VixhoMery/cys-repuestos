-- ============================================================
-- Snapshot del mes calendario anterior
-- Zona horaria comercial: Chile continental
-- ============================================================

CREATE OR REPLACE FUNCTION
  public.cys_monthly_report_snapshot(
    p_reference timestamptz
      DEFAULT NOW()
  )
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_timezone text :=
    'America/Santiago';

  v_reference_local timestamp;

  v_start_local timestamp;

  v_end_local timestamp;

  v_start_utc timestamptz;

  v_end_utc timestamptz;

  v_sales jsonb;
BEGIN
  v_reference_local :=
    timezone(
      v_timezone,
      p_reference
    );

  v_end_local :=
    date_trunc(
      'month',
      v_reference_local
    );

  v_start_local :=
    v_end_local -
    INTERVAL '1 month';

  v_start_utc :=
    v_start_local
      AT TIME ZONE
      v_timezone;

  v_end_utc :=
    v_end_local
      AT TIME ZONE
      v_timezone;

  SELECT COALESCE(
    jsonb_agg(
      jsonb_build_object(
        'id',
          s.id::integer,

        'seller',
          COALESCE(
            s.seller_email,
            'Usuario eliminado'
          ),

        'soldAt',
          s.sold_at,

        'total',
          s.total_amount,

        'paymentMethod',
          s.payment_method,

        'installments',
          s.installments,

        'items',
          COALESCE(
            (
              SELECT jsonb_agg(
                jsonb_build_object(
                  'productId',
                    si.product_id::integer,

                  'name',
                    si.product_name,

                  'quantity',
                    si.quantity,

                  'unitPrice',
                    si.unit_price,

                  'subtotal',
                    si.subtotal
                )
                ORDER BY
                  si.id
              )
              FROM
                public.sale_items si
              WHERE
                si.sale_id =
                  s.id
            ),
            '[]'::jsonb
          )
      )
      ORDER BY
        s.sold_at ASC,
        s.id ASC
    ),
    '[]'::jsonb
  )
  INTO
    v_sales
  FROM
    public.sales s
  WHERE
    s.sold_at >=
      v_start_utc
    AND
    s.sold_at <
      v_end_utc;

  RETURN jsonb_build_object(
    'periodKey',
      to_char(
        v_start_local,
        'YYYY-MM'
      ),

    'periodStartLocal',
      to_char(
        v_start_local,
        'YYYY-MM-DD'
      ),

    'periodEndLocal',
      to_char(
        v_end_local,
        'YYYY-MM-DD'
      ),

    'timezone',
      v_timezone,

    'sales',
      v_sales
  );
END;
$$;


