-- ============================================================
-- Registro de entregas de reportes
-- ============================================================

CREATE TABLE IF NOT EXISTS
  public.report_deliveries (
    id bigint
      GENERATED BY DEFAULT
      AS IDENTITY
      PRIMARY KEY,

    report_type text
      NOT NULL,

    period_key text
      NOT NULL,

    recipient_key text
      NOT NULL,

    status text
      NOT NULL
      DEFAULT 'sending',

    sales_count integer
      NOT NULL
      DEFAULT 0,

    total_amount bigint
      NOT NULL
      DEFAULT 0,

    provider_message_id text
      NULL,

    sent_at timestamptz
      NULL,

    last_error text
      NULL,

    created_at timestamptz
      NOT NULL
      DEFAULT NOW(),

    updated_at timestamptz
      NOT NULL
      DEFAULT NOW(),

    CONSTRAINT
      report_deliveries_type_valid
      CHECK (
        report_type IN (
          'monthly-sales'
        )
      ),

    CONSTRAINT
      report_deliveries_status_valid
      CHECK (
        status IN (
          'sending',
          'sent',
          'failed'
        )
      ),

    CONSTRAINT
      report_deliveries_sales_count_valid
      CHECK (
        sales_count >= 0
      ),

    CONSTRAINT
      report_deliveries_total_amount_valid
      CHECK (
        total_amount >= 0
      ),

    CONSTRAINT
      report_deliveries_unique_delivery
      UNIQUE (
        report_type,
        period_key,
        recipient_key
      )
  );

ALTER TABLE
  public.report_deliveries
ENABLE ROW LEVEL SECURITY;

